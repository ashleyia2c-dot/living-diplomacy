import { compactAction, validateReaction } from "./protocol.js";

export function luaString(value) {
  if (typeof value !== "string") throw new Error("luaString accepts text only");
  return `"${value
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\r/g, "\\r")
    .replace(/\n/g, "\\n")}"`;
}

// endsTalk: the ruler ended the audience for this turn. Packs before 0.45 ignore the
// extra argument.
export function renderInbox({ requestId, narrative, action, reaction, endsTalk = false }) {
  const compact = compactAction(action);
  const relation = validateReaction(reaction);
  return [
    "-- Generated by the local companion. Do not edit while the game is running.",
    "if llmdip_publish_response then",
    `  llmdip_publish_response(${luaString(requestId)}, ${luaString(narrative)}, ${luaString(compact)}, ${relation.delta}, ${luaString(relation.reason)}, ${endsTalk ? "true" : "false"})`,
    "end",
    ""
  ].join("\n");
}
