-- El idioma de la interfaz se le pregunta al propio juego: se pide una cadena vanilla
-- cuya traduccion oficial conocemos en los 13 idiomas (sacada de sus packs de
-- localizacion) y se compara. Asi no depende de que el companion este abierto, y un
-- inbox viejo no puede dejar la interfaz en otro idioma.
local LANGUAGE_PROBE_KEY = "uied_component_texts_localised_string_tx_total_attitude_NewState_Text_5c0047"
local LANGUAGE_PROBE = {
    en = "Total attitude value:",
    es = "Valor total de actitud:",
    fr = "Valeur totale de l'attitude :",
    de = "Gesamteinstellung:",
    it = "Valore totale atteggiamento:",
    ru = "Общий уровень отношения:",
    pl = "Całkowita wartość nastawienia:",
    cs = "Celkový postoj:",
    tr = "Toplam tutum değeri:",
    ko = "총 태도 가치:",
    pt = "Valor total da postura:",
    zh = "总体态度值：",
    tw = "總態度值："
}
local language_from_game = false
local probe_attempts = 0

-- Al cargar los scripts la localizacion puede no estar lista todavia; se reintenta en
-- las siguientes llamadas, con un tope para no preguntar eternamente si nunca responde.
local function detect_game_language()
    if language_from_game or probe_attempts >= 50 then return end
    probe_attempts = probe_attempts + 1
    local ok, text = pcall(function() return common.get_localised_string(LANGUAGE_PROBE_KEY) end)
    if not ok or type(text) ~= "string" then return end
    text = string.gsub(text, "^%s+", "")
    text = string.gsub(text, "%s+$", "")
    for code, label in pairs(LANGUAGE_PROBE) do
        if text == label then UI_LANG = code; language_from_game = true; return end
    end
end

-- El companion tambien manda el idioma, pero solo cuenta si el juego no lo ha dicho.
function llmdip_set_language(code)
    detect_game_language()
    if language_from_game then return end
    if type(code) == "string" and UI_TEXT[code] then UI_LANG = code end
end

function llmdip_language() detect_game_language(); return UI_LANG end

-- Solo el idioma que ha confirmado el juego; nil si todavia no lo sabemos. El puente
-- lo manda en cada peticion para que el companion escriba las cartas en ese idioma.
function llmdip_game_language()
    detect_game_language()
    if language_from_game then return UI_LANG end
    return nil
end

-- Un idioma incompleto cae al ingles clave por clave, nunca a un hueco en pantalla.
function llmdip_t(key)
    detect_game_language()
    local pack = UI_TEXT[UI_LANG]
    local value = pack and pack[key]
    if value == nil then value = UI_TEXT.en[key] end
    if value == nil then return key end
    return value
end
